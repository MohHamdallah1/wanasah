export type LedgerTextKey = keyof typeof ar;

export const ledgerText = (
  t: TFunction,
  language: string,
  key: LedgerTextKey,
  values: Record<string, unknown> = {},
): string => {
  const copy = language.toLowerCase().startsWith("ar") ? ar : en;
  return String(t(`inventoryLedger.cp10.${key}`, { defaultValue: copy[key], ...values }));
};

export const ledgerMovementLabel = (
  t: TFunction,
  language: string,
  type: string,
): string => {
  const key = `movement_${type}` as LedgerTextKey;
  if (key in ar) return ledgerText(t, language, key);
  return type;
};

export const ledgerBadgeClass = (type: string): string => {
  if (type === "INBOUND_SUPPLIER") return "bg-emerald-50 text-emerald-700 border-emerald-200";
  if (type === "INBOUND_CORRECTION") return "bg-purple-50 text-purple-700 border-purple-200";
  if (type.includes("STOCKTAKE") || type === "AUDIT_ADJUSTMENT") return "bg-amber-50 text-amber-800 border-amber-200";
  if (type.includes("TRANSFER")) return "bg-blue-50 text-blue-700 border-blue-200";
  if (type === "STATUS_CHANGE") return "bg-slate-100 text-slate-700 border-slate-200";
  return "bg-slate-50 text-slate-700 border-slate-200";
};

export const ledgerStatusLabel = (t: TFunction, language: string, status: string | null): string | null => {
  if (!status) return null;
  const key = `status_${status}` as LedgerTextKey;
  return key in ar ? ledgerText(t, language, key) : status;
};
