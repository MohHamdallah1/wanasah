export type BatchActionCopyKey = keyof typeof ar;

export const batchActionText = (
  t: TFunction,
  language: string,
  key: BatchActionCopyKey,
  values: Record<string, unknown> = {},
): string => {
  const copy = language.toLowerCase().startsWith("ar") ? ar : en;
  return String(
    t(`inventoryBatches.actions.${key}`, {
      defaultValue: copy[key],
      ...values,
    }),
  );
};
