export type BatchIndexCopyKey = keyof typeof ar;

export const batchIndexText = (
  t: TFunction,
  language: string,
  key: BatchIndexCopyKey,
  values: Record<string, unknown> = {},
): string => {
  const copy = language.toLowerCase().startsWith("ar") ? ar : en;
  return String(
    t(`inventoryBatches.index.${key}`, {
      defaultValue: copy[key],
      ...values,
    }),
  );
};
