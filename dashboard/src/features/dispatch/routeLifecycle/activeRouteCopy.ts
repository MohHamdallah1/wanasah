export type ActiveRouteTextKey=keyof typeof labels.en;
export function activeRouteText(language:string,key:ActiveRouteTextKey,vars:Record<string,string|number>={}):string {
  const locale=language.toLowerCase().startsWith("ar")?"ar":"en";
  let message:string=labels[locale][key];
  for(const [name,value] of Object.entries(vars)) message=message.split("{"+name+"}").join(String(value));
  return message;
}
