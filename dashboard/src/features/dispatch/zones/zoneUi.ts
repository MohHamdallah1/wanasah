export type ZoneTextKey = keyof typeof copy.en;
export function zoneText(language: string, key: ZoneTextKey, values: Record<string, string | number> = {}): string {
  const locale = language.toLowerCase().startsWith("ar") ? "ar" : "en";
  let value: string = copy[locale][key];
  for (const [name, replacement] of Object.entries(values)) value = value.split("{" + name + "}").join(String(replacement));
  return value;
}
export type ZoneFrequency = "7" | "14" | "30" | "custom";
export const frequencyFromDays = (days: number | null): ZoneFrequency =>
  days === 7 || days === 14 || days === 30 ? String(days) as ZoneFrequency : "custom";
export const daysFromFrequency = (frequency: string, customDays: number): number | null =>
  frequency === "7" || frequency === "14" || frequency === "30" ? Number(frequency) :
    frequency === "custom" && Number.isInteger(customDays) && customDays > 0 ? customDays : null;
